"""Compact a LightGBM booster + target-encoding tables into pmModel.json for the pure-TS evaluator (priceModel.ts).
Tree arrays per tree: f=feature idx, t=threshold, m=missing (0: NaN->0 then compare, 1: NaN goes left, 2: NaN goes right),
l/r=child (>=0 internal node index, <0 leaf ~idx), v=leaf values."""
def g7(x): return float(f"{x:.8g}")
def lv(x): return round(x, 6)
def compact(booster, te, rng):
    d = booster.dump_model(); trees = []
    for ti in d["tree_info"]:
        T = {"f": [], "t": [], "m": [], "l": [], "r": [], "v": []}
        def walk(n):
            if "split_index" not in n:
                T["v"].append(lv(n["leaf_value"])); return ~(len(T["v"]) - 1)
            i = len(T["f"]); T["f"].append(n["split_feature"]); T["t"].append(g7(n["threshold"]))
            T["m"].append(0 if n["missing_type"] == "None" else (1 if n["default_left"] else 2)); T["l"].append(0); T["r"].append(0)
            assert n["decision_type"] == "<=" and n["missing_type"] in ("None", "NaN")
            T["l"][i] = walk(n["left_child"]); T["r"][i] = walk(n["right_child"]); return i
        root = walk(ti["tree_structure"])
        if root < 0: T = {"f": [], "t": [], "m": [], "l": [], "r": [], "v": T["v"]}
        trees.append(T)
    r4 = lambda x: round(x, 5)
    tab = {lvl: {k: [r4(v[0]), v[1]] for k, v in t.items()} for lvl, t in te.tab.items()}
    return {"version": "pm-1", "features": d["feature_names"], "trees": trees, "te": {"g": r4(te.g), "K": list(te.K), **tab}, "range": rng}

def write_ts(model, path):
    import json
    with open(path, "w") as f:
        f.write("// AUTO-GENERATED by scripts/pricemodel/train.py (EXPORT=1). Do not edit. pm-1 LightGBM price model.\n")
        f.write("// deno-lint-ignore-file\nexport const PM_MODEL = " + json.dumps(model, separators=(",", ":")) + " as const;\n")
