"""Generate supabase/functions/_shared/priceModelBody.ts: most common advert body type per make|model.
Why: analyse-vehicle has no body type for most requests (the frontend does not send one), and pm-1 with body missing
scores 17.8% median error on the held-out set vs 15.2% with the true body; filling from this table gives 15.6%.
Usage: WORK=<clean.json dir> RAW=<harvest csv.gz> python scripts/pricemodel/body_modes.py"""
import os, json, pandas as pd
from features import norm_body, BODIES
c = pd.read_json(os.path.join(os.environ["WORK"], "clean.json")); h = pd.read_csv(os.environ["RAW"]); h["id"] = "gt" + h.listing_id.astype(str)
d = c.merge(h[["id", "body"]], on="id", how="left")
d = d[d.id.str.startswith("gt") & (d.search_tag == "harvest") & ~d.non_runner & ~d.held & (d.price >= 300) & d.body.notna()]
k = d.make.str.lower() + "|" + d.model.str.lower(); b = d.body.map(norm_body)
tab = pd.DataFrame({"k": k, "b": b}).groupby("k").b.agg(lambda s: s.value_counts().index[0])
out = os.environ.get("TS_OUT", "supabase/functions/_shared/priceModelBody.ts")
with open(out, "w") as f:
    f.write("// AUTO-GENERATED by scripts/pricemodel/body_modes.py from the harvest training pool. Do not edit by hand.\n"
            "// Most common advert body type per make|model (index into BODIES in priceModel.ts), used when the request has\n"
            "// no usable body type. Held-out pm-1 median error: 17.8% body missing -> 15.6% with this fill (15.2% true body).\n"
            "export const PM_BODY_MODE: Record<string, number> = {\n")
    f.write(",".join(f"{json.dumps(kk)}:{BODIES.index(v)}" for kk, v in sorted(tab.items())) + "\n};\n")
print(len(tab), "models ->", out)
