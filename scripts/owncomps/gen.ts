import { detectPerformanceVariant } from "../../supabase/functions/_shared/performance.ts";
const WORK = Deno.env.get("WORK") ?? "/tmp/owncomps";
const TODAY = new Date().toISOString().slice(0, 10);
const all = JSON.parse(Deno.readTextFileSync(`${WORK}/clean.json`)).filter((x: any) => !x.non_runner);
const rows = all.map((x: any) => {
  const needDesc = !detectPerformanceVariant(x.make, x.model, x.variant, "") && detectPerformanceVariant(x.make, x.model, x.variant, x.desc);
  const v = needDesc ? `${x.variant} ${String(x.desc).slice(0, 160).replace(/\s+/g, " ")}`.trim() : x.variant;
  return [x.make, x.model, v, x.year, x.mileage, x.fuel === "diesel" ? 1 : x.fuel === "hybrid" ? 2 : 0, x.gearbox === "automatic" ? 1 : 0, x.seller === "dealer" ? 1 : 0, x.price, x.cat_sn || x.no_mot ? 1 : 0];
});
Deno.writeTextFileSync(`${WORK}/ownCompsData.ts`, `// Generated by scripts/owncomps/rebuild.sh from base_listings.csv.gz + data/listings (cleaned: deduped, normalised, outliers dropped, non-runners removed).
// ${rows.length} UK asking prices (seed 2026-10-23 + daily harvest, rebuilt ${TODAY}). Do not hand-edit; regenerate.
// [make, model, variantOrTitle, year, mileage, fuel(0 petrol/1 diesel/2 hybrid), auto, dealer, price, catOrNoMot]
export const OWN_COMPS_COLLECTED = "${TODAY}";
export const OWN_COMPS_ROWS: [string, string, string, number, number, number, number, number, number, number][] = ${JSON.stringify(rows)};
`);
console.log(rows.length);
