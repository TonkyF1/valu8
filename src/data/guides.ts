export type Guide = {
  slug: string;
  path: string;
  title: string;
  description: string;
  h1: string;
  markdown: string;
  faqs: { question: string; answer: string }[];
};

const unquote = (v: string) => v.trim().replace(/^"(.*)"$/, "$1");

function blocks(markdown: string): string[] {
  return markdown.split(/\n[ \t]*\n/).map((b) => b.trim()).filter(Boolean);
}

/** Plain text: markdown links reduced to their text, emphasis markers removed. */
function plain(text: string): string {
  return text.replace(/\[([^\]]+)\]\([^)\s]+\)/g, "$1").replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
}

function extractFaqs(markdown: string): Guide["faqs"] {
  const all = blocks(markdown);
  const start = all.findIndex((b) => b === "## FAQs");
  if (start < 0) return [];
  const faqs: Guide["faqs"] = [];
  for (const block of all.slice(start + 1)) {
    if (block === "---" || block.startsWith("##")) break;
    const [first, ...rest] = block.split("\n");
    const m = first.trim().match(/^\*\*(.+\?)\*\*$/);
    if (!m || !rest.length) continue;
    faqs.push({ question: plain(m[1]), answer: plain(rest.join(" ")) });
  }
  return faqs;
}

export function parseGuide(source: string): Guide {
  const m = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error("Guide: missing front matter");
  const fields: Record<string, string> = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) fields[line.slice(0, i).trim()] = line.slice(i + 1);
  }
  const path = unquote(fields.slug ?? "");
  const slug = path.split("/").filter(Boolean).pop() ?? "";
  const markdown = m[2].replace(/^\n+/, "");
  const h1 = (markdown.match(/^# (.+)$/m)?.[1] ?? "").trim();
  if (!slug || !h1) throw new Error("Guide: missing slug or h1");
  return {
    slug,
    path: `/guides/${slug}`,
    title: unquote(fields.seo_title ?? ""),
    description: unquote(fields.meta_description ?? ""),
    h1,
    markdown,
    faqs: extractFaqs(markdown),
  };
}

export const GUIDES: Guide[] = GUIDE_SOURCES.map(parseGuide);

export function findGuide(slug: string | undefined): Guide | undefined {
  return GUIDES.find((g) => g.slug === slug);
}

function esc(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function inline(text: string): string {
  return esc(text)
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label: string, url: string) =>
      url.startsWith("/") ? `<a href="${url}">${label}</a>` : `<a href="${url}" target="_blank" rel="noopener noreferrer">${label}</a>`)
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/\*([^*]+)\*/g, "<em>$1</em>");
}

/** Minimal markdown renderer for exactly the constructs used in the guide files. */
export function guideBodyHtml(markdown: string): string {
  return blocks(markdown).map((block) => {
    if (block === "---") return "<hr />";
    const h = block.match(/^(#{1,3}) (.+)$/);
    if (h && !block.includes("\n")) return `<h${h[1].length}>${inline(h[2])}</h${h[1].length}>`;
    const lines = block.split("\n");
    if (lines.every((l) => l.startsWith("- "))) return `<ul>${lines.map((l) => `<li>${inline(l.slice(2))}</li>`).join("")}</ul>`;
    if (lines.every((l) => /^\d+\. /.test(l))) return `<ol>${lines.map((l) => `<li>${inline(l.replace(/^\d+\. /, ""))}</li>`).join("")}</ol>`;
    return `<p>${lines.map(inline).join("<br />")}</p>`;
  }).join("\n");
}

export function guideFaqJsonLd(guide: Guide): string {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: guide.faqs.map((f) => ({
      "@type": "Question",
      name: f.question,
      acceptedAnswer: { "@type": "Answer", text: f.answer },
    })),
  }).replace(/</g, "\\u003c");
}

export const GUIDES_INDEX_H1 = "Car valuation, buying and selling guides";

export function guidesIndexBodyHtml(): string {
  const items = GUIDES.map((g) => `<li><a href="${g.path}">${esc(g.h1)}</a><p>${esc(g.description)}</p></li>`).join("");
  return `<main id="main"><h1>${esc(GUIDES_INDEX_H1)}</h1><ul>${items}</ul></main>`;
}

export function guideArticleHtml(guide: Guide): string {
  return `<main id="main"><article>${guideBodyHtml(guide.markdown)}</article></main>`;
}
