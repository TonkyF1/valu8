const unquote = (v: string) => v.trim().replace(/^"(.*)"$/, "$1");

function blocks(markdown: string): string[] {
  return markdown.split(/\n[ \t]*\n/).map((b) => b.trim()).filter(Boolean);
}

/** Plain text: markdown links reduced to their text, emphasis markers removed. */
function plain(text: string): string {
  return text.replace(/\[([^\]]+)\]\([^)\s]+\)/g, "$1").replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
}

function extractFaqs(markdown: string): Guide["faqs"] {
  const all = blocks(markdown);
  const start = all.findIndex((b) => b === "## FAQs");
  if (start < 0) return [];
  const faqs: Guide["faqs"] = [];
  for (const block of all.slice(start + 1)) {
    if (block === "---" || block.startsWith("##")) break;
    const [first, ...rest] = block.split("\n");
    const m = first.trim().match(/^\*\*(.+\?)\*\*$/);
    if (!m || !rest.length) continue;
    faqs.push({ question: plain(m[1]), answer: plain(rest.join(" ")) });
  }
  return faqs;
}

export function parseGuide(source: string): Guide {
  const m = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error("Guide: missing front matter");
  const fields: Record<string, string> = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) fields[line.slice(0, i).trim()] = line.slice(i + 1);
  }
  const path = unquote(fields.slug ?? "");
  const slug = path.split("/").filter(Boolean).pop() ?? "";
  const markdown = m[2].replace(/^\n+/, "");
  const h1 = (markdown.match(/^# (.+)$/m)?.[1] ?? "").trim();
  if (!slug || !h1) throw new Error("Guide: missing slug or h1");
  return {
    slug,
    path: `/guides/${slug}`,
    title: unquote(fields.seo_title ?? ""),
    description: unquote(fields.meta_description ?? ""),
    h1,
    markdown,
    faqs: extractFaqs(markdown),
  };
}

export const GUIDES: Guide[] = GUIDE_SOURCES.map(parseGuide);

